import Foundation

/// Renders the main Caddyfile and per-site snippets.
///
/// Every value interpolated here is either operator configuration (validated in `Config`) or a manifest field
/// validated by `Manifest.parse`. All variable values are additionally emitted as quoted tokens.
public enum CaddyConfig {
    /// Quotes a token for the Caddyfile. Callers guarantee the absence of characters Caddy would interpret
    /// (`{`, `}`, `\`, backtick, control characters); this is a second line of defence.
    static func quote(_ s: String) -> String {
        precondition(!s.unicodeScalars.contains { $0.value < 0x20 || $0.value == 0x7F || "{}\\`".unicodeScalars.contains($0) },
                     "unsafe value reached Caddyfile renderer")
        return "\"" + s.replacingOccurrences(of: "\"", with: "\\\"") + "\""
    }

    public static func mainCaddyfile(_ config: Config, storage: Storage) -> String {
        var g: [String] = []
        g.append("\tadmin \(config.caddyAdmin)")
        g.append("\tpersist_config off")
        g.append("\tstorage file_system \(quote(storage.caddyState.path))")
        switch config.tlsMode {
        case .perSite, .wildcard:
            if let email = config.acmeEmail { g.append("\temail \(email)") }
        case .external:
            g.append("\tauto_https off")
        }
        if !config.trustedProxies.isEmpty {
            g.append("\tservers {")
            g.append("\t\ttrusted_proxies static \(config.trustedProxies.joined(separator: " "))")
            g.append("\t}")
        }
        g.append("\tlog {")
        g.append("\t\toutput stdout")
        g.append("\t\tformat json")
        g.append("\t}")

        let apiAddress = siteAddress(host: config.apiHost, config: config)
        // Allow a little room over the bundle limit for the manifest and form framing.
        let maxBody = config.maxUploadBytes + 1024 * 1024

        var out = """
        # Generated by gamehost from GAMEHOST_* environment at startup. Do not edit; changes are overwritten.
        {
        \(g.joined(separator: "\n"))
        }

        # Deploy API
        \(apiAddress) {
        \trequest_body {
        \t\tmax_size \(maxBody)
        \t}
        \treverse_proxy \(config.apiListenHost):\(config.apiListenPort) {
        \t\theader_up X-Gamehost-Client-IP {client_ip}
        \t}
        \tlog
        }

        # Sites (one generated snippet per site and preview)
        import \(quote(storage.snippetsDir.path + "/*.caddy"))

        """
        switch config.tlsMode {
        case .external:
            out += """

            # Unknown subdomains
            http://:\(config.externalPort) {
            \trespond 404
            }

            """
        case .perSite, .wildcard:
            out += """

            # Unknown subdomains over plain HTTP. Over HTTPS, unknown names have no certificate and none is requested.
            http:// {
            \trespond 404
            }

            """
        }
        return out
    }

    static func siteAddress(host: String, config: Config) -> String {
        switch config.tlsMode {
        case .external: return "http://\(host):\(config.externalPort)"
        case .perSite, .wildcard: return host
        }
    }

    /// The snippet for one site or preview, rendered from the manifest of the release it serves.
    public static func siteSnippet(key: String, manifest m: Manifest, config: Config, storage: Storage) -> String {
        var headers: [String] = [
            "X-Content-Type-Options \(quote("nosniff"))",
            "Cache-Control \(quote(m.cacheMaxAge > 0 ? "public, max-age=\(m.cacheMaxAge)" : "no-cache"))",
        ]
        if m.crossOriginIsolation {
            headers.append("Cross-Origin-Opener-Policy \(quote("same-origin"))")
            headers.append("Cross-Origin-Embedder-Policy \(quote("require-corp"))")
        }
        for h in m.customHeaders {
            precondition(Manifest.headerProblems(name: h.name, value: h.value).isEmpty, "unvalidated header")
            headers.append("\(h.name) \(quote(h.value))")
        }

        var lines: [String] = []
        lines.append("# Generated by gamehost for \(key). Do not edit; changes are overwritten.")
        lines.append("\(siteAddress(host: config.host(forKey: key), config: config)) {")
        lines.append("\troot * \(quote(storage.servedRoot(key).path))")
        lines.append("\tencode zstd gzip")
        lines.append("\theader {")
        lines += headers.map { "\t\t" + $0 }
        lines.append("\t}")
        if m.entry != "index.html" {
            precondition(Names.isPlainPathCharset(m.entry))
            lines.append("\trewrite / \(quote("/" + m.entry))")
        }
        lines.append("\tfile_server {")
        lines.append("\t\tprecompressed br gzip")
        lines.append("\t}")
        lines.append("\tlog")
        lines.append("}")
        return lines.joined(separator: "\n") + "\n"
    }
}
